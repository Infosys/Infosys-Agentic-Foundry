#!/bin/bash
# Hook 4 — PostTurn: Append mandatory ops disclaimer to every ccdops response.
#
# Reads IAF_RESPONSE (the agent's final answer), appends a fixed disclaimer,
# writes the result to stdout. HookRunner replaces the response with stdout
# when exit code is 0 and stdout is non-empty.
#
# Verify from chat UI:
#   Every ccdops response should end with the disclaimer line below.

DISCLAIMER="
---
⚠️ **Ops Advisory**: This analysis was generated by an AI agent. All recommended actions must be verified by the on-call engineer before execution. For P1 incidents, escalate to the CCD platform team immediately."

# Print original response + disclaimer
printf '%s%s' "$IAF_RESPONSE" "$DISCLAIMER"

exit 0
